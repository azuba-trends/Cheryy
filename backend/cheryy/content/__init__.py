@tool(
    name="content.summarize",
    description="Summarise a long text into a concise, useful summary.",
    parameters={
        "type": "object",
        "properties": {"text": {"type": "string"}, "max_words": {"type": "integer", "default": 200}, "style": {"type": "string", "default": "concise"}},
        "required": ["text"],
    },
    category="content",
)
async def content_summarize(text: str, max_words: int = 200, style: str = "concise") -> dict[str, Any]:
    reg = get_registry()
    llm = reg.llm()
    if llm is None:
        return {"error": "no provider"}
    user = f"Summarise the following text in <= {max_words} words, {style} style:\n\n{text[:60000]}"
    req = LLMRequest(messages=[LLMMessage(role="user", content=user)], max_tokens=512)
    resp = await reg.generate(req, capability=Capability.GENERAL)
    return {"summary": resp.content}